import fs from 'fs'
import path from 'path'
import { calculateMutationTestMetrics } from 'mutation-testing-metrics'

// Stryker's default JSON reporter path (see stryker.config.mjs's jsonReporter.fileName).
const mutationReportPath = path.join(process.cwd(), 'reports', 'mutation', 'mutation.json')

const publicDir = path.join(process.cwd(), 'public')
if (!fs.existsSync(publicDir)) {
  fs.mkdirSync(publicDir, { recursive: true })
}

if (fs.existsSync(mutationReportPath)) {
  try {
    const report = JSON.parse(fs.readFileSync(mutationReportPath, 'utf8'))

    // Use Stryker's own official metrics calculator (same package its html/clear-text
    // reporters use internally) rather than hand-computing killed/valid — it correctly
    // excludes ignored/compile-error/runtime-error mutants from the denominator per
    // Stryker's documented scoring rules.
    const { systemUnderTestMetrics } = calculateMutationTestMetrics(report)
    const { mutationScore, killed, survived, timeout, noCoverage, totalValid } =
      systemUnderTestMetrics.metrics
    const pct = Math.round(mutationScore * 100) / 100

    let color = 'red'
    if (pct >= 95) color = 'brightgreen'
    else if (pct >= 90) color = 'green'
    else if (pct >= 80) color = 'yellowgreen'
    else if (pct >= 70) color = 'yellow'
    else if (pct >= 60) color = 'orange'

    const badgeData = {
      schemaVersion: 1,
      label: 'mutation score',
      message: `${pct}%`,
      color,
    }
    fs.writeFileSync(
      path.join(publicDir, 'badge-mutation.json'),
      JSON.stringify(badgeData, null, 2)
    )
    console.log('[generate-mutation-badge] Generated public/badge-mutation.json')
    console.log(
      `[generate-mutation-badge] mutationScore=${pct}% killed=${killed} survived=${survived} timeout=${timeout} noCoverage=${noCoverage} totalValid=${totalValid}`
    )

    const generatedDir = path.join(process.cwd(), 'src', 'lib', 'generated')
    if (!fs.existsSync(generatedDir)) {
      fs.mkdirSync(generatedDir, { recursive: true })
    }
    const statsFile = [
      '// Generated by scripts/generate-mutation-badge.mjs from the real Stryker mutation',
      '// report (reports/mutation/mutation.json). Do not edit by hand — regenerated by',
      '// running `npm run mutation && npm run mutation:badge` and committing the diff.',
      '// See docs/specs/TESTING.md for the mutation-testing scope and methodology.',
      'export const MUTATION_STATS = {',
      `  mutationScore: '${pct}%',`,
      '} as const',
      '',
    ].join('\n')
    fs.writeFileSync(path.join(generatedDir, 'mutationStats.ts'), statsFile)
    console.log('[generate-mutation-badge] Generated src/lib/generated/mutationStats.ts')
  } catch (err) {
    console.error('[generate-mutation-badge] Failed to generate mutation badge:', err)
    process.exitCode = 1
  }
} else {
  console.log(
    '[generate-mutation-badge] reports/mutation/mutation.json not found — run `npm run mutation` first, skipping'
  )
}
